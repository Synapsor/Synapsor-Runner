import { canonicalJsonDigest } from "@synapsor-runner/protocol";
import type { ControlPolicyEvent } from "@synapsor-runner/proposal-store";
import type { BoundProjectPolicyStore } from "./control-policy-store.js";

export type PolicyPublicationSettlement =
  | { state: "committed" | "cancelled"; epoch: number }
  | { state: "unconfirmed"; reason: "receipt_unavailable" | "receipt_mismatch" | "cancellation_unconfirmed" };

/** Internal recovery of an already authorized publication, never a way to
 * activate its candidate. Cancellation competes for the original epoch and
 * event identity; it changes no policy pointer and fences a delayed COMMIT. */
export async function settlePolicyPublication(input: {
  binding: BoundProjectPolicyStore;
  expectedEpoch: number;
  event: { event_id: string; actor: string; digest: string };
}): Promise<PolicyPublicationSettlement> {
  const event = structuredClone(input.event);
  const { binding, expectedEpoch } = input;
  if (!Number.isSafeInteger(expectedEpoch) || expectedEpoch < 0 || expectedEpoch >= Number.MAX_SAFE_INTEGER
    || !event.event_id || !event.actor || !/^sha256:[a-f0-9]{64}$/u.test(event.digest)) {
    throw new Error("POLICY_PUBLICATION_RECORD_INVALID: restore the exact saved publication record.");
  }
  const cancellation: ControlPolicyEvent = {
    event_id: event.event_id, actor: event.actor, occurred_at: new Date().toISOString(),
    receipt: { operation: "cancel_unconfirmed_policy_publication", publication_event_digest: event.digest,
      authority_changed: false, source_database_changed: false },
  };
  const classify = (recorded: ControlPolicyEvent & { epoch: number }): PolicyPublicationSettlement => {
    if (recorded.epoch !== expectedEpoch + 1) return { state: "unconfirmed", reason: "receipt_mismatch" };
    const { epoch: _epoch, ...recordedEvent } = recorded;
    if (canonicalJsonDigest(recordedEvent) === event.digest) {
      return { state: "committed", epoch: recorded.epoch };
    }
    // The cancellation's execution timestamp is generated by the recovering
    // process. Its identity, actor and exact original-event digest are stable.
    if (recorded.event_id === event.event_id && recorded.actor === event.actor
      && canonicalJsonDigest(recorded.receipt) === canonicalJsonDigest(cancellation.receipt)) {
      return { state: "cancelled", epoch: recorded.epoch };
    }
    return { state: "unconfirmed", reason: "receipt_mismatch" };
  };
  let recorded;
  try { recorded = await binding.repository.event(binding.deployment_id, event.event_id); }
  catch { return { state: "unconfirmed", reason: "receipt_unavailable" }; }
  if (recorded) return classify(recorded);
  try {
    const epoch = await binding.repository.commit({ deployment_id: binding.deployment_id, expected_epoch: expectedEpoch,
      revisions: [], active: [], drafts: [], event: cancellation });
    return { state: "cancelled", epoch };
  } catch {
    // Original COMMIT, cancellation, or another policy update may have won.
    // Only an exact durable receipt permits success or rollback of bindings.
    try { recorded = await binding.repository.event(binding.deployment_id, event.event_id); }
    catch { return { state: "unconfirmed", reason: "receipt_unavailable" }; }
    return recorded ? classify(recorded) : { state: "unconfirmed", reason: "cancellation_unconfirmed" };
  }
}
